CREATE FUNCTION meetings.upsert_planning_meeting(p_zcal_event_id character varying, p_user_id uuid, p_advisor_email character varying, p_title character varying, p_scheduled_at timestamp with time zone, p_duration_minutes integer, p_is_cancelled boolean DEFAULT false, p_platform character varying DEFAULT 'zoom'::character varying, p_meeting_url text DEFAULT NULL::text, p_meeting_external_id character varying DEFAULT NULL::character varying, p_meeting_passcode character varying DEFAULT NULL::character varying, p_incorporation_id uuid DEFAULT NULL::uuid, p_is_workflow boolean DEFAULT false)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'meetings', 'public'
AS $function$
DECLARE
  v_meeting_id       uuid;
  v_status           meetings.meeting_status;
  v_category         meetings.meeting_category;
  v_advisor_id       uuid;
  v_incorporation_id uuid;
  v_intent_id        uuid;
  v_is_new           boolean := false;
BEGIN
  -- 1. Determinar status
  IF p_is_cancelled THEN
    v_status := 'cancelled';
  ELSE
    v_status := 'scheduled';
  END IF;

  -- 2. Resolver incorporation_id
  v_incorporation_id := p_incorporation_id;

  -- Si es workflow y no viene incorporation_id explícito,
  -- buscar en booking_intents
  IF p_is_workflow AND v_incorporation_id IS NULL THEN
    SELECT bi.id, bi.incorporation_id
    INTO v_intent_id, v_incorporation_id
    FROM meetings.booking_intents bi
    WHERE bi.user_id = p_user_id
      AND bi.category = 'workflow_stage'
      AND bi.fulfilled_at IS NULL
    ORDER BY bi.created_at DESC
    LIMIT 1;
  END IF;

  -- 3. Determinar category
  IF v_incorporation_id IS NOT NULL THEN
    v_category := 'workflow_stage';
  ELSE
    v_category := 'consultation';
  END IF;

  -- 4. Resolver advisor_id por email
  SELECT user_id INTO v_advisor_id
  FROM public.usuarios
  WHERE correo = p_advisor_email
  LIMIT 1;

  -- 5. UPSERT
  INSERT INTO meetings.planning_meetings (
    user_id, advisor_id, incorporation_id, category,
    title, status, scheduled_at, duration_minutes,
    platform, meeting_url, meeting_external_id, meeting_passcode,
    zcal_event_id, completed_at, created_at, updated_at
  ) VALUES (
    p_user_id,
    COALESCE(v_advisor_id, p_user_id),
    v_incorporation_id,
    v_category,
    p_title,
    v_status,
    p_scheduled_at,
    p_duration_minutes,
    p_platform,
    p_meeting_url,
    p_meeting_external_id,
    p_meeting_passcode,
    p_zcal_event_id,
    CASE WHEN p_is_cancelled THEN now() ELSE NULL END,
    now(),
    now()
  )
  ON CONFLICT (zcal_event_id) DO UPDATE SET
    status       = EXCLUDED.status,
    scheduled_at = EXCLUDED.scheduled_at,
    duration_minutes = EXCLUDED.duration_minutes,
    meeting_url  = EXCLUDED.meeting_url,
    meeting_external_id = EXCLUDED.meeting_external_id,
    meeting_passcode = EXCLUDED.meeting_passcode,
    title        = EXCLUDED.title,
    completed_at = CASE
                     WHEN EXCLUDED.status = 'cancelled' THEN now()
                     ELSE meetings.planning_meetings.completed_at
                   END,
    updated_at   = now()
  RETURNING id, (xmax = 0) INTO v_meeting_id, v_is_new;

  -- 6. Marcar el intent como fulfilled (si usamos uno)
  IF v_intent_id IS NOT NULL AND v_is_new THEN
    UPDATE meetings.booking_intents
    SET fulfilled_at = now(),
        meeting_id   = v_meeting_id
    WHERE id = v_intent_id;
  END IF;

  RETURN jsonb_build_object(
    'success', true,
    'meeting_id', v_meeting_id,
    'operation', CASE WHEN v_is_new THEN 'created' ELSE 'updated' END,
    'status', v_status::text,
    'category', v_category::text,
    'advisor_resolved', v_advisor_id IS NOT NULL,
    'incorporation_id', v_incorporation_id,
    'intent_used', v_intent_id IS NOT NULL
  );

EXCEPTION WHEN OTHERS THEN
  RETURN jsonb_build_object(
    'success', false,
    'error', SQLERRM,
    'error_code', SQLSTATE
  );
END;
$function$;
