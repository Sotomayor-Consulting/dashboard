CREATE FUNCTION public.apply_referral_code(p_user_id uuid, p_code text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_partner uuid;
  v_already uuid;
begin
  if p_code is null or btrim(p_code) = '' then
    raise exception 'Código de referido vacío';
  end if;

  select user_id into v_partner
  from public.usuarios
  where codigo_de_partner = upper(trim(p_code));

  if v_partner is null then
    raise exception 'Código de referido inválido';
  end if;

  if v_partner = p_user_id then
    raise exception 'No puede referirse a sí mismo';
  end if;

  select referido_por into v_already
  from public.usuarios
  where user_id = p_user_id;

  if v_already is not null then
    raise exception 'El usuario ya tiene un partner asignado';
  end if;

  update public.usuarios
     set referido_por = v_partner
   where user_id = p_user_id;

  insert into public.referidos(partner_id, referido_id, code)
  values (v_partner, p_user_id, upper(trim(p_code)));
end;
$function$;
GRANT ALL ON FUNCTION public.apply_referral_code(uuid, text) TO authenticated;
GRANT ALL ON FUNCTION public.apply_referral_code(uuid, text) TO service_role;
