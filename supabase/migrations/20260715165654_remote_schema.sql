CREATE FUNCTION public.registrar_pago_desde_stripe(p_payment_intent jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_attrs          jsonb := p_payment_intent;
  v_pi_id          text;
  v_status         text;
  v_metadata       jsonb;
  v_user_id        uuid;
  v_plan_id        int;
  v_empresa_id     uuid;
  v_order_id       uuid;
  v_amount         numeric;
  v_anchor_service bigint;
  v_payment        orders.payments%rowtype;
begin
  if v_attrs is null or v_attrs->>'id' is null then
    raise exception 'PaymentIntent jsonb inválido o sin id' using errcode = 'P0001';
  end if;
  v_pi_id := v_attrs->>'id';

  v_status   := coalesce(v_attrs->>'status', '');
  v_metadata := coalesce(v_attrs->'metadata', '{}'::jsonb);
  v_user_id  := nullif(v_metadata->>'user_id', '')::uuid;
  v_empresa_id := nullif(v_metadata->>'empresa_incorporacion_id', '')::uuid;
  v_plan_id  := nullif(v_metadata->>'plan_id', '')::int;
  v_order_id := nullif(v_metadata->>'order_id', '')::uuid;

  if v_status <> 'succeeded' then
    raise exception 'PaymentIntent % tiene status %, se esperaba succeeded',
      v_pi_id, v_status using errcode = 'P0001';
  end if;

  v_amount := coalesce(
    nullif(v_attrs->>'amount_received', '')::numeric,
    nullif(v_attrs->>'amount', '')::numeric
  );
  if v_amount is null then
    raise exception 'PaymentIntent % sin amount', v_pi_id using errcode = 'P0001';
  end if;
  v_amount := v_amount / 100.0;

  if v_order_id is not null and not exists (select 1 from orders.orders where id = v_order_id) then
    v_order_id := null;
  end if;

  -- Idempotencia: si este PaymentIntent ya fue registrado (eventos previos
  -- del mismo pago), reutilizar la orden de ese pago en vez de crear otra.
  if v_order_id is null then
    select p.order_id into v_order_id
    from orders.payments p
    where p.provider_transaction_id = v_pi_id;
  end if;

  if v_order_id is null then
    if v_user_id is null or v_plan_id is null then
      raise exception 'Falta order_id o (user_id+plan_id) en metadata del PaymentIntent %',
        v_pi_id using errcode = 'P0001';
    end if;
    select coalesce(
      (select spl.service_id from catalogs.service_plan_lines spl
       where spl.service_plan_id = v_plan_id order by spl.service_id limit 1),
      7
    ) into v_anchor_service;

    insert into orders.orders (user_id, incorporation_id, status, currency, metadata)
    values (v_user_id, v_empresa_id, 'confirmed', 'usd',
            jsonb_build_object('created_by','webhook_fallback','plan_id',v_plan_id))
    returning id into v_order_id;

    insert into orders.order_lines
      (order_id, service_id, service_plan_id, service_name, service_plan_name, unit_price, quantity)
    select v_order_id, v_anchor_service, v_plan_id, svc.name, sp.name, v_amount, 1
    from catalogs.service_plans sp
    join catalogs.services svc on svc.id = v_anchor_service
    where sp.id = v_plan_id;
  end if;

  insert into orders.payments
    (order_id, provider, provider_transaction_id, provider_metadata, status, amount, paid_at)
  values
    (v_order_id, 'stripe', v_pi_id, v_attrs, 'succeeded', v_amount, now())
  on conflict (provider_transaction_id) do update
    set status            = 'succeeded',
        amount            = excluded.amount,
        provider_metadata = excluded.provider_metadata,
        paid_at           = now(),
        updated_at        = now()
  returning * into v_payment;

  update orders.orders set status = 'confirmed', updated_at = now()
  where id = v_order_id and status is distinct from 'confirmed';

  return to_jsonb(v_payment);
end;
$function$;
GRANT ALL ON FUNCTION public.registrar_pago_desde_stripe(jsonb) TO service_role;
