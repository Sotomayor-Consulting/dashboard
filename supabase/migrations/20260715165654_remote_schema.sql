CREATE FUNCTION public.workflow_advance_stage(p_workflow_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'workflow', 'public'
AS $function$
DECLARE
  v_next_instance uuid;
  v_next_stage_catalog_id int;
  v_next_sla int;
BEGIN
  SELECT s.id, s.stage_id, c.sla_hours
  INTO v_next_instance, v_next_stage_catalog_id, v_next_sla
  FROM workflow.incorporation_workflow_stages s
  JOIN workflow.workflow_stage_catalog c ON c.id = s.stage_id
  WHERE s.workflow_id = p_workflow_id AND s.status = 'not_started'
  ORDER BY s.display_order ASC LIMIT 1;

  IF v_next_instance IS NULL THEN
    UPDATE workflow.incorporation_workflows
    SET status = 'completed', completed_at = now(), current_stage_id = NULL, updated_at = now()
    WHERE id = p_workflow_id;
    RETURN jsonb_build_object('ok', true, 'workflow_completed', true);
  END IF;

  UPDATE workflow.incorporation_workflow_stages
  SET status = 'in_progress', started_at = now(),
      due_at = CASE WHEN v_next_sla IS NOT NULL THEN now() + (v_next_sla || ' hours')::interval ELSE NULL END
  WHERE id = v_next_instance;

  UPDATE workflow.incorporation_workflows
  SET current_stage_id = v_next_stage_catalog_id, updated_at = now()
  WHERE id = p_workflow_id;

  RETURN jsonb_build_object('ok', true, 'current_stage_id', v_next_stage_catalog_id);
END; $function$;
