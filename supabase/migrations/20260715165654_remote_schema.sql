CREATE VIEW orders.order_admin_details WITH (security_invoker=true) AS SELECT o.id,
    o.order_number,
    o.status,
    o.currency,
    o.seen_by_ops,
    o.created_at,
    o.user_id,
    NULLIF(TRIM(BOTH FROM concat_ws(' '::text, u.nombre, u.apellido)), ''::text) AS client_name,
    u.correo AS client_email,
    o.incorporation_id,
    inc.principal_name AS incorporation_name,
    pl.plan_slug,
    pl.plan_name,
    COALESCE(pl.show_prices, false) AS show_prices,
    pay.provider_transaction_id,
    pay.payment_status,
    pay.paid_at,
    lt.total,
        CASE
            WHEN COALESCE(pl.show_prices, false) THEN bd.lines
            ELSE bd.lines_no_price
        END AS lines
   FROM ((((((orders.orders o
     LEFT JOIN public.usuarios u ON ((u.user_id = o.user_id)))
     LEFT JOIN public.incorporations inc ON ((inc.id = o.incorporation_id)))
     LEFT JOIN LATERAL ( SELECT ol.service_plan_id,
            sp.slug AS plan_slug,
            sp.name AS plan_name,
            sp.show_prices
           FROM (orders.order_lines ol
             JOIN catalogs.service_plans sp ON ((sp.id = ol.service_plan_id)))
          WHERE ((ol.order_id = o.id) AND (ol.service_plan_id IS NOT NULL))
          ORDER BY ol.created_at
         LIMIT 1) pl ON (true))
     LEFT JOIN LATERAL ( SELECT sum((ol.unit_price * (ol.quantity)::numeric)) AS total
           FROM orders.order_lines ol
          WHERE (ol.order_id = o.id)) lt ON (true))
     LEFT JOIN LATERAL ( SELECT jsonb_agg(x.line ORDER BY x.sort, x.ord) AS lines,
            jsonb_agg(x.line_np ORDER BY x.sort, x.ord) AS lines_no_price
           FROM ( SELECT 0 AS sort,
                    s.id AS ord,
                    jsonb_build_object('service_name', s.name, 'service_plan_name', pl.plan_name, 'unit_price', spl.price, 'quantity', 1) AS line,
                    jsonb_build_object('service_name', s.name, 'service_plan_name', pl.plan_name, 'quantity', 1) AS line_np
                   FROM (catalogs.service_plan_lines spl
                     JOIN catalogs.services s ON ((s.id = spl.service_id)))
                  WHERE (spl.service_plan_id = pl.service_plan_id)
                UNION ALL
                 SELECT 0 AS sort,
                    ol.service_id AS ord,
                    jsonb_build_object('service_name', ol.service_name, 'service_plan_name', ol.service_plan_name, 'unit_price', ol.unit_price, 'quantity', ol.quantity) AS jsonb_build_object,
                    jsonb_build_object('service_name', ol.service_name, 'service_plan_name', ol.service_plan_name, 'quantity', ol.quantity) AS jsonb_build_object
                   FROM orders.order_lines ol
                  WHERE ((ol.order_id = o.id) AND (ol.service_plan_id IS NOT NULL) AND (NOT (EXISTS ( SELECT 1
                           FROM catalogs.service_plan_lines spl2
                          WHERE (spl2.service_plan_id = pl.service_plan_id)))))
                UNION ALL
                 SELECT 1 AS sort,
                    ol.service_id AS ord,
                    jsonb_build_object('service_name', ol.service_name, 'service_plan_name', NULL::unknown, 'unit_price', ol.unit_price, 'quantity', ol.quantity) AS jsonb_build_object,
                    jsonb_build_object('service_name', ol.service_name, 'service_plan_name', NULL::unknown, 'quantity', ol.quantity) AS jsonb_build_object
                   FROM orders.order_lines ol
                  WHERE ((ol.order_id = o.id) AND (ol.service_plan_id IS NULL))) x) bd ON (true))
     LEFT JOIN LATERAL ( SELECT p.provider_transaction_id,
            p.status AS payment_status,
            p.paid_at
           FROM orders.payments p
          WHERE (p.order_id = o.id)
          ORDER BY (p.status = 'succeeded'::orders.payment_status) DESC, p.created_at DESC
         LIMIT 1) pay ON (true));
