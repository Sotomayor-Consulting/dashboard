CREATE FUNCTION documents.auto_share_on_client_visible()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
	v_owner_id uuid;
begin
	if new.visibility <> 'client_visible' then
		return new;
	end if;

	if tg_op = 'UPDATE' and old.visibility = 'client_visible' then
		return new;
	end if;

	if new.case_id is null then
		return new;
	end if;

	select user_id into v_owner_id
	from public.incorporations
	where id = new.case_id;

	if v_owner_id is null then
		return new;
	end if;

	insert into documents.document_shares (
		document_id,
		case_id,
		shared_with_user_id,
		shared_by_user_id,
		share_status,
		shared_at,
		updated_at
	) values (
		new.id,
		new.case_id,
		v_owner_id,
		coalesce(new.updated_by, new.uploaded_by),
		'active',
		now(),
		now()
	)
	on conflict (document_id, shared_with_user_id)
	do update set
		share_status = 'active',
		shared_at = now(),
		updated_at = now()
	where documents.document_shares.share_status <> 'active';

	return new;
end;
$function$;
GRANT ALL ON FUNCTION documents.auto_share_on_client_visible() TO service_role;
