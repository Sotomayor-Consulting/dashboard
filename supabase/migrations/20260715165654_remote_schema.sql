CREATE FUNCTION public.notifications_broadcast_trigger()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  _topic text;
  _event text;
  _op    text := tg_op;
begin
  _topic := 'user:' || coalesce(new.user_id, old.user_id)::text || ':notifications';

  if tg_op = 'INSERT' then
    _event := 'notification_created';
    begin
      perform realtime.broadcast_changes(_topic, _event, _op, tg_table_name, tg_table_schema, new, null);
    exception
      when undefined_function then
        perform realtime.send(_topic, _event, to_jsonb(new), true); -- true => private
      when others then
        -- swallow
        null;
    end;
    return new;

  elsif tg_op = 'UPDATE' then
    if (old.is_read is distinct from new.is_read) or (old.leido_en is distinct from new.leido_en) then
      _event := 'notification_status_changed';
    else
      _event := 'notification_updated';
    end if;

    begin
      perform realtime.broadcast_changes(_topic, _event, _op, tg_table_name, tg_table_schema, new, old);
    exception
      when undefined_function then
        perform realtime.send(_topic, _event, jsonb_build_object('new', to_jsonb(new), 'old', to_jsonb(old)), true);
      when others then
        null;
    end;
    return new;

  elsif tg_op = 'DELETE' then
    _event := 'notification_deleted';
    begin
      perform realtime.broadcast_changes(_topic, _event, _op, tg_table_name, tg_table_schema, null, old);
    exception
      when undefined_function then
        perform realtime.send(_topic, _event, to_jsonb(old), true);
      when others then
        null;
    end;
    return old;
  end if;

  return coalesce(new, old);
end;
$function$;
GRANT ALL ON FUNCTION public.notifications_broadcast_trigger() TO service_role;
