CREATE FUNCTION orders.trg_payment_set_incorporation_state()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_incorp uuid;
  v_slug   text;
begin
  if NEW.status <> 'succeeded' then return NEW; end if;
  select o.incorporation_id into v_incorp from orders.orders o where o.id = NEW.order_id;
  if v_incorp is null then return NEW; end if;

  select sp.slug into v_slug
  from orders.order_lines ol
  join catalogs.service_plans sp on sp.id = ol.service_plan_id
  where ol.order_id = NEW.order_id and ol.service_plan_id is not null
  order by ol.created_at limit 1;

  if v_slug = 'diseno' then
    update public.incorporations ei set state = 'upgrade', updated_at = now()
    where ei.id = v_incorp and ei.state is distinct from 'upgrade';
  else
    update public.incorporations ei set state = 'active', updated_at = now()
    where ei.id = v_incorp and ei.state is distinct from 'active';
  end if;
  return NEW;
end;
$function$;
