CREATE FUNCTION orders.trg_payment_succeeded_workflow()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_incorp   uuid;
  v_plan_id  int;
  v_existing uuid;
begin
  if NEW.status = 'succeeded' AND (TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM 'succeeded') then
    select o.incorporation_id into v_incorp from orders.orders o where o.id = NEW.order_id;
    if v_incorp is null then return NEW; end if;

    select ol.service_plan_id::int into v_plan_id
    from orders.order_lines ol
    where ol.order_id = NEW.order_id and ol.service_plan_id is not null
    order by ol.created_at limit 1;
    if v_plan_id is null then return NEW; end if;

    select id into v_existing from workflow.incorporation_workflows where incorporation_id = v_incorp;
    if v_existing is null then
      perform workflow.create_workflow_for_incorporation(v_incorp, v_plan_id);
    else
      perform workflow.append_missing_stages_for_plan(v_incorp, v_plan_id);
    end if;
  end if;
  return NEW;
end;
$function$;
