CREATE FUNCTION public.procesar_orden_odoo(p_user_id uuid, p_odoo_partner_id bigint, p_odoo_invoice_id bigint, p_odoo_sale_order_id bigint, p_servicio_template_id bigint, p_monto numeric, p_perfil jsonb DEFAULT '{}'::jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_servicio_id   uuid;
  v_empresa_id    uuid;
  v_pago          public.pagos%rowtype;
  v_existing_pago public.pagos%rowtype;
  v_synthetic_pi  text := 'odoo:' || p_odoo_invoice_id::text;
  v_meta          jsonb;
  v_nombre        text;
  v_apellido      text;
  v_telefono      text;
  v_dir1          text;
  v_dir2          text;
  v_correo        text;
  v_display       text;
begin
  select * into v_existing_pago from public.pagos
   where odoo_invoice_id = p_odoo_invoice_id limit 1;
  if v_existing_pago.id_pagos is not null then
    return jsonb_build_object('status','already_processed','pago', to_jsonb(v_existing_pago));
  end if;

  select id_servicios into v_servicio_id
    from public.servicios
   where odoo_product_template_id = p_servicio_template_id
     and servicio_activo = true
   limit 1;

  if v_servicio_id is null then
    raise exception 'Servicio Odoo template_id=% no mapeado o inactivo', p_servicio_template_id;
  end if;

  select raw_user_meta_data into v_meta from auth.users where id = p_user_id;
  v_meta := coalesce(v_meta, '{}'::jsonb);

  v_nombre   := coalesce(nullif(p_perfil->>'nombre',''),           nullif(v_meta->>'nombre',''),    nullif(v_meta->>'first_name',''),  nullif(v_meta->>'name',''));
  v_apellido := coalesce(nullif(p_perfil->>'apellido',''),         nullif(v_meta->>'apellido',''),  nullif(v_meta->>'last_name',''),   nullif(v_meta->>'lastName',''));
  v_telefono := coalesce(nullif(p_perfil->>'telefono',''),         nullif(v_meta->>'telefono',''),  nullif(v_meta->>'phone',''));
  v_dir1     := coalesce(nullif(p_perfil->>'direccion_linea1',''), nullif(v_meta->>'direccion_linea1',''));
  v_dir2     := coalesce(nullif(p_perfil->>'direccion_linea2',''), nullif(v_meta->>'direccion_linea2',''));
  v_correo   := coalesce(nullif(p_perfil->>'correo',''),           nullif(v_meta->>'email',''));
  v_display  := nullif(trim(concat_ws(' ', v_nombre, v_apellido)), '');

  insert into public.usuarios (
    user_id, nombre, apellido, correo, telf,
    direccion_linea1, direccion_linea2, odoo_partner_id
  ) values (
    p_user_id, v_nombre, v_apellido, v_correo, v_telefono,
    v_dir1, v_dir2, p_odoo_partner_id
  )
  on conflict (user_id) do update set
    nombre           = coalesce(nullif(public.usuarios.nombre,''),   excluded.nombre),
    apellido         = coalesce(nullif(public.usuarios.apellido,''), excluded.apellido),
    correo           = coalesce(nullif(public.usuarios.correo,''),   excluded.correo),
    telf             = coalesce(nullif(public.usuarios.telf,''),     excluded.telf),
    direccion_linea1 = coalesce(nullif(public.usuarios.direccion_linea1,''), excluded.direccion_linea1),
    direccion_linea2 = coalesce(nullif(public.usuarios.direccion_linea2,''), excluded.direccion_linea2),
    odoo_partner_id  = coalesce(public.usuarios.odoo_partner_id,     excluded.odoo_partner_id);

  if v_display is not null then
    update auth.users
       set raw_user_meta_data = coalesce(raw_user_meta_data, '{}'::jsonb)
           || jsonb_build_object(
                'display_name', coalesce(nullif(raw_user_meta_data->>'display_name',''), v_display),
                'full_name',    coalesce(nullif(raw_user_meta_data->>'full_name',''),    v_display),
                'nombre',       coalesce(nullif(raw_user_meta_data->>'nombre',''),       v_nombre),
                'apellido',     coalesce(nullif(raw_user_meta_data->>'apellido',''),     v_apellido)
              )
     where id = p_user_id;
  end if;

  -- Crear incorporación
  insert into public.incorporations (
    user_id, state,
    porcentaje_de_incorporacion, source, odoo_sale_order_id
  ) values (
    p_user_id, 'En proceso',
    1, 'odoo', p_odoo_sale_order_id
  )
  returning id into v_empresa_id;

  insert into public.pagos (
    user_id, servicio_id, empresa_incorporacion_id,
    amount, status, stripe_payment_intent_id,
    odoo_invoice_id, odoo_sale_order_id, source
  ) values (
    p_user_id, v_servicio_id, v_empresa_id,
    (p_monto * 100)::bigint, 'succeeded', v_synthetic_pi,
    p_odoo_invoice_id, p_odoo_sale_order_id, 'odoo'
  )
  returning * into v_pago;

  return jsonb_build_object(
    'status','created',
    'empresa_id',  v_empresa_id,
    'servicio_id', v_servicio_id,
    'display_name', v_display,
    'pago',        to_jsonb(v_pago)
  );
end;
