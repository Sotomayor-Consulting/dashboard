CREATE FUNCTION orders.trg_order_confirmed_cancel_stale()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_plan_slug text;
  v_base_slugs text[] := array['basico','estandar','business'];
begin
  if NEW.status <> 'confirmed' or NEW.incorporation_id is null then
    return NEW;
  end if;
  if TG_OP = 'UPDATE' and OLD.status = 'confirmed' then
    return NEW;
  end if;

  select sp.slug into v_plan_slug
  from orders.order_lines ol
  join catalogs.service_plans sp on sp.id = ol.service_plan_id
  where ol.order_id = NEW.id and ol.service_plan_id is not null
  order by ol.created_at limit 1;
  if v_plan_slug is null then return NEW; end if;

  update orders.orders o
  set status = 'canceled',
      updated_at = now(),
      metadata = coalesce(o.metadata, '{}'::jsonb) || jsonb_build_object(
        'canceled_reason', 'superseded_by_confirmed_order',
        'superseded_by', NEW.id::text,
        'canceled_at', now()
      )
  where o.incorporation_id = NEW.incorporation_id
    and o.id <> NEW.id
    and o.status = 'pending_payment'
    and exists (
      select 1
      from orders.order_lines ol2
      join catalogs.service_plans sp2 on sp2.id = ol2.service_plan_id
      where ol2.order_id = o.id
        and (
          (v_plan_slug = any(v_base_slugs) and sp2.slug = any(v_base_slugs))
          or sp2.slug = v_plan_slug
        )
    );

  return NEW;
end;
$function$;
