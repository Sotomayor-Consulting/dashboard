CREATE FUNCTION public.workflow_client_snapshot(p_incorporation_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'workflow'
AS $function$
declare
	v_workflow jsonb;
	v_stages jsonb;
	v_tasks jsonb;
begin
	select (
		to_jsonb(w)
		|| jsonb_build_object(
			'current_stage',
			to_jsonb(c)
		)
	)
	into v_workflow
	from workflow.incorporation_workflows w
	left join workflow.workflow_stage_catalog c on c.id = w.current_stage_id
	where w.incorporation_id = p_incorporation_id
	limit 1;

	if v_workflow is null then
		return jsonb_build_object(
			'workflow', null,
			'stages', '[]'::jsonb,
			'tasks', '[]'::jsonb
		);
	end if;

	select coalesce(
		jsonb_agg(
			to_jsonb(s)
			|| jsonb_build_object('catalog', to_jsonb(c))
			order by s.display_order
		),
		'[]'::jsonb
	)
	into v_stages
	from workflow.incorporation_workflow_stages s
	join workflow.workflow_stage_catalog c on c.id = s.stage_id
	join workflow.incorporation_workflows w on w.id = s.workflow_id
	where w.incorporation_id = p_incorporation_id;

	select coalesce(
		jsonb_agg(to_jsonb(t) order by t.display_order),
		'[]'::jsonb
	)
	into v_tasks
	from workflow.incorporation_tasks t
	where t.incorporation_id = p_incorporation_id;

	return jsonb_build_object(
		'workflow', v_workflow,
		'stages', v_stages,
		'tasks', v_tasks
	);
end;
$function$;
