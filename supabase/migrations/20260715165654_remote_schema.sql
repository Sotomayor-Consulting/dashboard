CREATE FUNCTION workflow.create_workflow_for_incorporation(p_incorporation_id uuid, p_plan_id integer)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'workflow', 'public'
AS $function$
DECLARE
  v_workflow_id uuid;
  v_first_stage_id int;
  v_stage record;
  v_stage_instance_id uuid;
BEGIN
  SELECT id INTO v_workflow_id FROM workflow.incorporation_workflows WHERE incorporation_id = p_incorporation_id;
  IF v_workflow_id IS NOT NULL THEN RETURN v_workflow_id; END IF;

  IF NOT EXISTS (SELECT 1 FROM workflow.workflow_stage_plan_applicability WHERE plan_id = p_plan_id) THEN
    RETURN NULL;
  END IF;

  SELECT sc.id INTO v_first_stage_id
  FROM workflow.workflow_stage_catalog sc
  JOIN workflow.workflow_stage_plan_applicability a ON a.stage_id = sc.id
  WHERE a.plan_id = p_plan_id AND sc.is_active = true
  ORDER BY sc.display_order ASC LIMIT 1;

  INSERT INTO workflow.incorporation_workflows (incorporation_id, current_stage_id, status, started_at)
  VALUES (p_incorporation_id, v_first_stage_id, 'in_progress', now())
  RETURNING id INTO v_workflow_id;

  FOR v_stage IN
    SELECT sc.*
    FROM workflow.workflow_stage_catalog sc
    JOIN workflow.workflow_stage_plan_applicability a ON a.stage_id = sc.id
    WHERE a.plan_id = p_plan_id AND sc.is_active = true
    ORDER BY sc.display_order ASC
  LOOP
    INSERT INTO workflow.incorporation_workflow_stages (
      workflow_id, stage_id, status, display_order, started_at, due_at
    )
    VALUES (
      v_workflow_id,
      v_stage.id,
      CASE WHEN v_stage.id = v_first_stage_id THEN 'in_progress'::workflow.workflow_status ELSE 'not_started'::workflow.workflow_status END,
      v_stage.display_order,
      CASE WHEN v_stage.id = v_first_stage_id THEN now() ELSE NULL END,
      CASE WHEN v_stage.id = v_first_stage_id AND v_stage.sla_hours IS NOT NULL
           THEN now() + (v_stage.sla_hours || ' hours')::interval ELSE NULL END
    )
    RETURNING id INTO v_stage_instance_id;

    INSERT INTO workflow.incorporation_tasks (
      workflow_stage_id, incorporation_id, template_task_id, title, description,
      status, priority, assigned_role, display_order
    )
    SELECT
      v_stage_instance_id, p_incorporation_id, tt.id, tt.title, tt.description,
      'pending'::workflow.task_status, tt.default_priority, tt.default_assigned_role, tt.display_order
    FROM workflow.task_templates tt
    WHERE tt.stage_id = v_stage.id AND tt.is_active = true
    ORDER BY tt.display_order;
  END LOOP;

  RETURN v_workflow_id;
END; $function$;
