CREATE FUNCTION public.workflow_complete_task(p_task_id uuid, p_user_id uuid DEFAULT NULL::uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'workflow', 'public'
AS $function$
DECLARE
  v_stage_id uuid;
  v_workflow_id uuid;
  v_stage_catalog_id int;
  v_all_done boolean;
  v_auto_advance boolean;
BEGIN
  UPDATE workflow.incorporation_tasks
  SET status = 'completed', completed_at = now(), completed_by = p_user_id, updated_at = now()
  WHERE id = p_task_id
  RETURNING workflow_stage_id INTO v_stage_id;

  IF v_stage_id IS NULL THEN RETURN jsonb_build_object('ok', false, 'error', 'task not found'); END IF;

  SELECT NOT EXISTS (
    SELECT 1 FROM workflow.incorporation_tasks
    WHERE workflow_stage_id = v_stage_id AND status NOT IN ('completed','skipped','cancelled')
  ) INTO v_all_done;

  IF NOT v_all_done THEN RETURN jsonb_build_object('ok', true, 'stage_completed', false); END IF;

  UPDATE workflow.incorporation_workflow_stages
  SET status = 'completed', completed_at = now()
  WHERE id = v_stage_id
  RETURNING workflow_id, stage_id INTO v_workflow_id, v_stage_catalog_id;

  SELECT auto_advance INTO v_auto_advance FROM workflow.workflow_stage_catalog WHERE id = v_stage_catalog_id;

  IF v_auto_advance THEN
    PERFORM public.workflow_advance_stage(v_workflow_id);
    RETURN jsonb_build_object('ok', true, 'stage_completed', true, 'advanced', true);
  END IF;

  RETURN jsonb_build_object('ok', true, 'stage_completed', true, 'advanced', false);
END; $function$;
GRANT ALL ON FUNCTION public.workflow_complete_task(uuid, uuid) TO authenticated;
GRANT ALL ON FUNCTION public.workflow_complete_task(uuid, uuid) TO service_role;
CREATE FUNCTION public.workflow_record_approval(p_stage_id uuid, p_decision text, p_comments text DEFAULT NULL::text, p_user_id uuid DEFAULT NULL::uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'workflow', 'public'
AS $function$
declare
	v_incorp uuid;
	v_next_round smallint;
	v_workflow_id uuid;
	v_actor uuid;
begin
	v_actor := coalesce(p_user_id, auth.uid());
	if v_actor is null then
		return jsonb_build_object('ok', false, 'error', 'missing user');
	end if;

	select w.incorporation_id, s.workflow_id
	into v_incorp, v_workflow_id
	from workflow.incorporation_workflow_stages s
	join workflow.incorporation_workflows w on w.id = s.workflow_id
	where s.id = p_stage_id;

	if v_incorp is null then
		return jsonb_build_object('ok', false, 'error', 'stage not found');
	end if;

	select coalesce(max(round), 0) + 1
	into v_next_round
	from workflow.approval_records
	where workflow_stage_id = p_stage_id;

	insert into workflow.approval_records (
		incorporation_id,
		workflow_stage_id,
		round,
		decision,
		decided_by,
		comments
	)
	values (
		v_incorp,
		p_stage_id,
		v_next_round,
		p_decision::workflow.approval_decision,
		v_actor,
		p_comments
	);

	if p_decision::workflow.approval_decision = 'approved'::workflow.approval_decision then
		update workflow.incorporation_workflow_stages
		set
			status = 'completed',
			completed_at = coalesce(completed_at, now())
		where id = p_stage_id
			and status <> 'completed';

		perform public.workflow_advance_stage(v_workflow_id);

		return jsonb_build_object(
			'ok',
			true,
			'round',
			v_next_round,
			'stage_completed',
			true,
			'advanced',
			true
		);
	end if;

	return jsonb_build_object('ok', true, 'round', v_next_round, 'advanced', false);
end;
$function$;
