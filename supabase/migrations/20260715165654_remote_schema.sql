CREATE FUNCTION workflow.reset_stage(p_stage_id uuid, p_reset_by uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'workflow', 'public'
AS $function$
DECLARE
  v_stage    workflow.incorporation_workflow_stages%ROWTYPE;
  v_old_status text;
  v_tasks_reset int;
BEGIN
  -- 1. Obtener el stage
  SELECT * INTO v_stage
  FROM workflow.incorporation_workflow_stages
  WHERE id = p_stage_id;

  IF v_stage.id IS NULL THEN
    RETURN jsonb_build_object('success', false, 'error', 'Stage no encontrado');
  END IF;

  v_old_status := v_stage.status::text;

  -- 2. Resetear tareas del stage a pending
  UPDATE workflow.incorporation_tasks
  SET status = 'pending',
      completed_at = NULL,
      completed_by = NULL,
      started_at = NULL,
      updated_at = now()
  WHERE workflow_stage_id = p_stage_id
    AND status NOT IN ('cancelled');

  GET DIAGNOSTICS v_tasks_reset = ROW_COUNT;

  -- 3. Cambiar stage a in_progress
  UPDATE workflow.incorporation_workflow_stages
  SET status = 'in_progress',
      completed_at = NULL,
      started_at = COALESCE(started_at, now())
  WHERE id = p_stage_id;

  RETURN jsonb_build_object(
    'success', true,
    'stage_id', p_stage_id,
    'old_status', v_old_status,
    'new_status', 'in_progress',
    'tasks_reset', v_tasks_reset,
    'reset_by', p_reset_by,
    'reset_at', now()
  );
END;
$function$;
GRANT ALL ON FUNCTION workflow.reset_stage(uuid, uuid) TO authenticated;
GRANT ALL ON FUNCTION workflow.reset_stage(uuid, uuid) TO service_role;
