CREATE FUNCTION public.generate_unique_partner_code(code_len integer DEFAULT 10)
 RETURNS text
 LANGUAGE plpgsql
AS $function$
declare
  len          int := greatest(6, coalesce(code_len, 10)); -- mínimo 6
  bytes_needed int := (len + 1) / 2;                       -- ceil(len/2)
  candidate    text;
  exists_code  boolean;
begin
  loop
    candidate := upper(substr(encode(gen_random_bytes(bytes_needed), 'hex'), 1, len));
    select exists(select 1 from public.usuarios where codigo_de_partner = candidate)
      into exists_code;
    exit when not exists_code; -- sale cuando NO existe
  end loop;
  return candidate;
end;
$function$;
